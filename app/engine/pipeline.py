"""One call: request dict -> files on disk + manifest dict."""
import json
import os
import time

import numpy as np
import soundfile as sf

from .duck import apply_ducking, load_narration
from .errors import EngineError
from .mix import lufs, make_mix, true_peak_db
from .plan import build_plan
from .render import BASE_GAINS, ROLE, STEMS, render_stems

ENGINE_VERSION = "1.0.0"


def validate(req):
    d = req.get("duration_s")
    if not isinstance(d, (int, float)) or not 5 <= d <= 300:
        raise EngineError("INVALID_DURATION", "duration_s must be a number between 5 and 300", details={"duration_s": d})


def generate(req: dict, outdir: str, only_stems=None, prior_stems: dict | None = None,
             progress=None, renderer=None, provider_info: dict | None = None):
    progress = progress or (lambda pct: None)
    renderer = renderer or render_stems
    t0 = time.time()
    validate(req)
    out = req.get("output") or {}
    target = float(out.get("target_lufs", -16))
    formats = out.get("formats") or ["wav", "mp3"]
    plan = build_plan(req)
    progress(10)
    os.makedirs(os.path.join(outdir, "stems"), exist_ok=True)

    t1 = time.time()
    new = renderer(plan, only_stems)
    stems = {**(prior_stems or {}), **new}
    stems = {n: stems[n] for n in STEMS}
    t_render = time.time() - t1
    progress(60)

    t2 = time.time()
    stems, gains, mix, mw = make_mix(stems, BASE_GAINS, plan.sr, target)
    t_mix = time.time() - t2
    progress(80)

    N = plan.N
    assert all(len(s) == N for s in stems.values()) and len(mix) == N
    sf.write(os.path.join(outdir, "mix.wav"), mix, plan.sr, subtype="PCM_24")
    for n, s in stems.items():
        sf.write(os.path.join(outdir, "stems", f"{n}.wav"), s, plan.sr, subtype="PCM_24")
    duck_info = None
    if req.get("narration_url"):
        narr = load_narration(req["narration_url"], plan.sr)
        depth = (req.get("ducking") or {}).get("depth_db", 12.0)
        ducked, duck_info, dw = apply_ducking(mix, plan.sr, narr, depth)
        mw += dw
        sf.write(os.path.join(outdir, "mix_ducked.wav"), ducked, plan.sr, subtype="PCM_24")
    if "mp3" in formats:
        try:
            sf.write(os.path.join(outdir, "mix.mp3"), mix, plan.sr, format="MP3")
        except Exception as e:  # libsndfile without mp3 support
            mw.append({"code": "MP3_UNAVAILABLE", "message": f"mp3 export failed: {e}"})

    manifest = {
        "engine": {"name": "incubrix-procedural-music", "version": ENGINE_VERSION},
        "providers": [provider_info or {"name": "procedural", "version": ENGINE_VERSION, "kind": "local synthesis (numpy)",
                                         "licence": "own code, no external models or samples"}],
        "request": {k: v for k, v in req.items() if k != "narration_url"},
        "seed": plan.seed, "variants": plan.variants,
        "tempo_bpm": round(plan.bpm, 4), "key": plan.key_name, "time_signature": "4/4",
        "duration_s": plan.duration_s, "sample_rate": plan.sr, "samples": N,
        "style": plan.style,
        "sections": [{k: s[k] for k in ("requested_start_s", "start_s", "start_bar", "mood", "energy")} for s in plan.sections],
        "grid": {"bar_len_s": round(plan.bar_len, 6), "n_bars": plan.n_bars,
                 "bar_times_s": [round(b * plan.bar_len, 4) for b in range(plan.n_bars)],
                 "beat_times_s": [round(i * plan.bar_len / 4, 4) for i in range(plan.n_bars * 4) if i * plan.bar_len / 4 < plan.duration_s]},
        "ending": "loop (no ending)" if plan.loop else f"final hit on bar line at {plan.hit_bar * plan.bar_len:.3f}s, then fade to silence",
        "stems": {n: {"file": f"stems/{n}.wav", "gain": gains[n], "produced_by": ROLE[n] + " (numpy synthesis, own code)",
                      "variant": plan.variants.get(n, 0)} for n in STEMS},
        "mix_formula": "mix = sum(stems[n] * gain[n])",
        "loudness": {"integrated_lufs": round(lufs(mix, plan.sr), 2), "true_peak_dbtp": round(true_peak_db(mix, plan.sr), 2),
                     "target_lufs": target},
        "timings_s": {"plan_and_render": round(t_render, 3), "mix": round(t_mix, 3), "total": round(time.time() - t0, 3)},
        "ducking": duck_info,
        "cost_estimate_usd": 0.0,
        "licences": [{"component": "all audio", "licence": "Generated by original code; no samples, loops, or models. Output is free of third-party rights."}],
        "warnings": plan.warnings + mw,
    }
    with open(os.path.join(outdir, "music_manifest.json"), "w") as f:
        json.dump(manifest, f, indent=2)
    return manifest, stems
